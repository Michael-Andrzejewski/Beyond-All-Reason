# ---------------------------------------------------------------- config ----
function Find-BarDataDir {
    $candidates = @(
        (Join-Path $env:LOCALAPPDATA 'Programs\Beyond-All-Reason\data'),
        'C:\Program Files\Beyond-All-Reason\data'
    )
    foreach ($c in $candidates) { if (Test-Path (Join-Path $c 'engine')) { return $c } }
    return $null
}

function Find-SpringExe([string]$dataDir) {
    if (-not $dataDir) { return $null }
    $engineRoot = Join-Path $dataDir 'engine'
    if (-not (Test-Path $engineRoot)) { return $null }
    $exe = Get-ChildItem $engineRoot -Directory | Sort-Object Name -Descending |
        ForEach-Object { Join-Path $_.FullName 'spring.exe' } |
        Where-Object { Test-Path $_ } | Select-Object -First 1
    return $exe
}

