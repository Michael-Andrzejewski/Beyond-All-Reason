# --------------------------------------------------------------- presets ----
function Get-Presets {
    $list = @()
    Get-ChildItem $PresetDir -Filter '*.json' | Sort-Object Name | ForEach-Object {
        try { $list += (Get-Content $_.FullName -Raw | ConvertFrom-Json) } catch { }
    }
    return $list
}

# ---------------------------------------------------------- script maker ----
function New-HostScript {
    param($p)  # hashtable of current UI settings
    $mo = New-Object System.Text.StringBuilder
    [void]$mo.AppendLine("		micro_wars_enabled=1;")
    [void]$mo.AppendLine("		experimentallegionfaction=1;")
    if ($p.touchdown) {
        [void]$mo.AppendLine("		micro_wars_touchdown=1;")
        if ($p.attackerSlot -gt 0) { [void]$mo.AppendLine("		touchdown_attacker_slot=$($p.attackerSlot);") }
        [void]$mo.AppendLine("		touchdown_win_score=$($p.winScore);")
    }
    if ($p.wipeoutOnly) { [void]$mo.AppendLine("		micro_wars_wipeout_only=1;") }
    [void]$mo.AppendLine("		round_time=$($p.roundTimeMin);")
    for ($i = 1; $i -le 2; $i++) {
        $pl = $p.players[$i - 1]
        if ($pl.initial)      { [void]$mo.AppendLine("		reinforcement_initial_p$i=$($pl.initial);") }
        if ($pl.interval -gt 0 -and $pl.wave) {
            [void]$mo.AppendLine("		reinforcement_interval_p$i=$($pl.interval);")
            [void]$mo.AppendLine("		reinforcement_wave_p$i=$($pl.wave);")
            if ($pl.waveAlt) {
                [void]$mo.AppendLine("		reinforcement_wave_alt_p$i=$($pl.waveAlt);")
                [void]$mo.AppendLine("		reinforcement_wave_alt_every_p$i=$($pl.altEvery);")
            }
        }
    }
    [void]$mo.AppendLine("		units_per_round=$($p.unitsPerRound);")
    [void]$mo.AppendLine("		micro_wars_show_timer=1;")
    [void]$mo.Append("		micro_wars_commander_radar=1;")

    @"
// Generated by Micro Wars Lobby $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')
[GAME]
{
	GameType=Beyond All Reason `$VERSION;
	Mapname=$($p.map);

	HostIP=0.0.0.0;
	HostPort=$($script:Config.hostPort);
	IsHost=1;
	MyPlayerName=$($p.hostName);
