function Get-UiSettings {
    $attackerSlot = $cmbAttacker.SelectedIndex   # 0 = both, 1 = p1, 2 = p2
    return @{
        map          = $txtMap.Text.Trim()
        roundTimeMin = [int]$numTime.Value
        unitsPerRound = [int]$numMult.Value
        touchdown    = $chkTouchdown.Checked
        wipeoutOnly  = $chkWipeout.Checked
        winScore     = [int]$numScore.Value
        attackerSlot = $attackerSlot
        hostName     = $(if ($script:Config.role -eq 'Host') { $txtMyName.Text.Trim() } else { $txtOppName.Text.Trim() })
        joinName     = $(if ($script:Config.role -eq 'Host') { $txtOppName.Text.Trim() } else { $txtMyName.Text.Trim() })
        players      = @(
            @{ initial = $p1.initial.Text.Trim(); wave = $p1.wave.Text.Trim(); interval = [int]$p1.interval.Value; waveAlt = $p1.waveAlt.Text.Trim(); altEvery = [int]$p1.altEvery.Value },
            @{ initial = $p2.initial.Text.Trim(); wave = $p2.wave.Text.Trim(); interval = [int]$p2.interval.Value; waveAlt = $p2.waveAlt.Text.Trim(); altEvery = [int]$p2.altEvery.Value }
        )
    }
}

function Set-UiFromPreset($pr) {
    if ($pr.map)                       { $txtMap.Text = $pr.map }
    if ($null -ne $pr.roundTimeMin)    { $numTime.Value = [math]::Max($numTime.Minimum, [math]::Min($numTime.Maximum, [int]$pr.roundTimeMin)) }
    if ($null -ne $pr.unitsPerRound)   { $numMult.Value = [math]::Max(1, [int]$pr.unitsPerRound) }
    $chkTouchdown.Checked = [bool]$pr.touchdown
    $chkWipeout.Checked   = [bool]$pr.wipeoutOnly
    if ($null -ne $pr.winScore)        { $numScore.Value = [math]::Max($numScore.Minimum, [math]::Min($numScore.Maximum, [int]$pr.winScore)) }
    if ($null -ne $pr.attackerSlot)    { $cmbAttacker.SelectedIndex = [math]::Max(0, [math]::Min(2, [int]$pr.attackerSlot)) }
    $boxes = @($p1, $p2)
    for ($i = 0; $i -lt 2; $i++) {
        $pl = $pr.players[$i]
        $b = $boxes[$i]
        $b.initial.Text = "$($pl.initial)"
        $b.wave.Text    = "$($pl.wave)"
        $b.waveAlt.Text = "$($pl.waveAlt)"
        $iv = 0; if ($null -ne $pl.interval) { $iv = [int]$pl.interval }
        $ae = 2; if ($null -ne $pl.altEvery -and [int]$pl.altEvery -ge 1) { $ae = [int]$pl.altEvery }
        $b.interval.Value = [math]::Max(0, [math]::Min(600, $iv))
        $b.altEvery.Value = [math]::Min(50, $ae)
    }
    $lblPresetDesc.Text = "$($pr.description)"
}

