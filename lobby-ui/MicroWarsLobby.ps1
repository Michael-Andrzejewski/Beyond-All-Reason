	NumAllyTeams=2;

	[MODOPTIONS]
	{
$($mo.ToString())
	}

	[PLAYER0]
	{
		Name=$($p.hostName);
		Team=0;
	}
	[PLAYER1]
	{
		Name=$($p.joinName);
		Team=1;
	}

	[TEAM0]
	{
		TeamLeader=0;
		AllyTeam=0;
		RgbColor=0.9 0.1 0.1;
		Side=Armada;
	}
	[TEAM1]
	{
		TeamLeader=1;
		AllyTeam=1;
		RgbColor=0.1 0.3 0.9;
		Side=Cortex;
	}

	[ALLYTEAM0]
	{
		NumAllies=0;
		StartRectLeft=0;
		StartRectRight=1;
		StartRectTop=0;
		StartRectBottom=0.30;
	}
	[ALLYTEAM1]
	{
		NumAllies=0;
		StartRectLeft=0;
		StartRectRight=1;
		StartRectTop=0.70;
		StartRectBottom=1;
	}
}
"@
}

