    $obj = [ordered]@{
        name = $name; description = $desc
        map = $s.map; roundTimeMin = $s.roundTimeMin; unitsPerRound = $s.unitsPerRound
        touchdown = $s.touchdown; wipeoutOnly = $s.wipeoutOnly
        winScore = $s.winScore; attackerSlot = $s.attackerSlot
        players = $s.players
    }
    $safe = ($name -replace '[^\w\- ]', '') -replace ' +', '-'
    $obj | ConvertTo-Json -Depth 5 | Set-Content -Path (Join-Path $PresetDir "$safe.json") -Encoding utf8
    Refresh-Presets
    $cmbPreset.SelectedIndex = [array]::IndexOf(@($script:Presets | ForEach-Object { $_.name }), $name)
    $lblStatus.Text = "Preset saved: $name"
})

