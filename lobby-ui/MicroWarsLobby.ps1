$SyncFiles = @(
    @{ url = 'https://raw.githubusercontent.com/Michael-Andrzejewski/Beyond-All-Reason/micro-wars-files/luarules/gadgets/game_micro_wars.lua'; rel = 'luarules\gadgets\game_micro_wars.lua' },
    @{ url = 'https://raw.githubusercontent.com/Michael-Andrzejewski/Beyond-All-Reason/micro-wars-files/modoptions.lua'; rel = 'modoptions.lua' },
    @{ url = 'https://raw.githubusercontent.com/Michael-Andrzejewski/Beyond-All-Reason/micro-wars-files/gamedata/unitdefs.lua'; rel = 'gamedata\unitdefs.lua' }
)

$btnSync.Add_Click({
    Sync-ConfigFromUi
    $sdd = Join-Path $script:Config.dataDir 'games\MicroWars.sdd'
    if (-not (Test-Path $sdd)) {
        $txtSyncLog.AppendText("ERROR: MicroWars.sdd not found at $sdd`r`nInstall the game first (see the setup guide).`r`n")
        return
    }
    $txtSyncLog.AppendText("Syncing mod files into $sdd ...`r`n")
    $ok = $true
    foreach ($f in $SyncFiles) {
        $dest = Join-Path $sdd $f.rel
        try {
            $tmp = "$dest.tmp"
            & curl.exe -sSfL -o $tmp $f.url
            if ($LASTEXITCODE -ne 0) { throw "curl exit $LASTEXITCODE" }
            Move-Item -Force $tmp $dest
            $txtSyncLog.AppendText("  OK  $($f.rel)`r`n")
        } catch {
            $ok = $false
            $txtSyncLog.AppendText("  FAIL $($f.rel): $_`r`n")
        }
    }
    if ($ok) {
        (Get-Item $sdd).LastWriteTime = Get-Date   # bust the engine's checksum cache
        $txtSyncLog.AppendText("Done. Checksum cache refreshed. You are ready to join.`r`n")
        $lblStatus.Text = 'Mod files synced.'
    } else {
        $txtSyncLog.AppendText("Sync had errors. Check your internet connection and try again.`r`n")
    }
})

