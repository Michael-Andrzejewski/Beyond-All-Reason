# ------------------------------------------------------------ game launch ---
$script:GameProc = $null

function Start-Game([string]$scriptPath, [System.Windows.Forms.Label]$statusLabel) {
    $spring = Find-SpringExe $script:Config.dataDir
    if (-not $spring) {
        [System.Windows.Forms.MessageBox]::Show("Could not find spring.exe under:`n$($script:Config.dataDir)`n`nIs Beyond All Reason installed?", 'Micro Wars Lobby') | Out-Null
        return $false
    }
    Get-Process spring -ErrorAction SilentlyContinue | Stop-Process -Force -ErrorAction SilentlyContinue
    $script:GameProc = Start-Process -FilePath $spring `
        -ArgumentList @('--write-dir', $script:Config.dataDir, '--isolation', $scriptPath) `
        -PassThru
    $statusLabel.Text = "Game running (pid $($script:GameProc.Id)). This window stays open. You will return here when the game closes."
    return $true
}

